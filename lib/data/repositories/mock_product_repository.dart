  static final Map<String, List<Product>> _categoryProductCache = {};
  static final Map<String, Product> _idProductCache = {};

  static void _ensureCache() {
    if (_idProductCache.isEmpty) {
      for (final p in _products) {
        _idProductCache[p.id] = p;
        _categoryProductCache.putIfAbsent(p.categoryId, () => []).add(p);
      }
    }
  }

  static List<Product> getAllProducts() => List.unmodifiable(_products);

  static Product? getProductById(String id) {
    _ensureCache();
    return _idProductCache[id];
  }

  static List<Product> getProductsByCategory(String categoryId) {
    _ensureCache();
    var resolvedId = categoryId;
    if (!_categoryProductCache.containsKey(categoryId)) {
      if (categoryId == 'cat_produce') resolvedId = 'cat_vegetables';
      if (categoryId == 'cat_care') resolvedId = 'cat_personal_care';
      if (categoryId == 'cat_cleaning') resolvedId = 'cat_home_essentials';
      if (categoryId == 'cat_staples' ||
          categoryId == 'cat_snacks' ||
          categoryId == 'cat_drinks' ||
          categoryId == 'cat_instant' ||
          categoryId == 'cat_sweets' ||
          categoryId == 'cat_tea_coffee') {
        resolvedId = 'cat_groceries';
      }
    }
    return List.unmodifiable(_categoryProductCache[resolvedId] ?? const []);
  }

  static List<Product> searchProducts(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return [];
    return _products.where((p) {
      return p.name.toLowerCase().contains(clean) ||
          p.brand.toLowerCase().contains(clean) ||
          p.subcategory.toLowerCase().contains(clean);
    }).toList();
  }

  static List<Product> getBestsellers() {
    return _products.where((p) => p.ratingCount >= 10000).toList();
  }

  static List<Product> sortProducts(List<Product> products, ProductSortOption sortOption) {
    final list = List<Product>.from(products);
    switch (sortOption) {
      case ProductSortOption.popular:
        list.sort((a, b) => b.ratingCount.compareTo(a.ratingCount));
        break;
      case ProductSortOption.priceLowToHigh:
        list.sort((a, b) => a.price.compareTo(b.price));
        break;
      case ProductSortOption.priceHighToLow:
        list.sort((a, b) => b.price.compareTo(a.price));
        break;
      case ProductSortOption.discount:
        list.sort((a, b) => b.discountPercent.compareTo(a.discountPercent));
        break;
    }
    return list;
  }
}

enum ProductSortOption {
  popular('Popularity'),
  priceLowToHigh('Price: Low to High'),
  priceHighToLow('Price: High to Low'),
  discount('Highest Discount');

  final String label;
  const ProductSortOption(this.label);
}
